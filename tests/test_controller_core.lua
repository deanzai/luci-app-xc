local t = require "testlib"

local function read_file(path)
  local handle = assert(io.open(path, "rb"))
  local value = assert(handle:read("*a"))
  handle:close()
  return value
end

t.test("core endpoints are POST-only and size limited", function()
  local source = read_file("luasrc/controller/xc.lua")
  t.contains(source, 'post_entry({ "admin", "services", "xc", "core-upload" }, "action_core_upload")')
  t.contains(source, 'post_entry({ "admin", "services", "xc", "core-activate" }, "action_core_activate")')
  t.contains(source, 'post_entry({ "admin", "services", "xc", "core-rollback" }, "action_core_rollback")')
  t.contains(source, 'post_entry({ "admin", "services", "xc", "core-delete" }, "action_core_delete")')
  t.contains(source, "local function require_post(maximum)")
  t.contains(source, "CORE_UPLOAD_MAX")
end)

t.test("core upload only submits the binary field", function()
  local view = read_file("luasrc/view/xc/core.htm")
  t.contains(view, 'form.append("core_file"')
  t.eq(view:find('form.append("sha256"', 1, true), nil)
  t.eq(view:find('form.append("note"', 1, true), nil)
  t.contains(view, 'data-core-token="<%=token%>"')
  local controller = read_file("luasrc/controller/xc.lua")
  t.eq(controller:find('http.formvalue("sha256")', 1, true), nil)
  t.eq(controller:find('http.formvalue("note")', 1, true), nil)
end)

t.test("core upload validates the automatically hashed binary without user metadata", function()
  local source = read_file("luasrc/controller/xc.lua")
