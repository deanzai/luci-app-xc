t.test("controller records core lifecycle operations without secrets", function()
  local source = read_file("luasrc/controller/xc.lua")
  t.contains(source, 'local function core_event(runtime_instance, message, value)')
  t.contains(source, 'core_event(runtime_instance, "core upload completed", installed)')
  t.contains(source, 'core_result(runtime_instance, value, "core activation")')
  t.contains(source, 'core_result(runtime_instance, value, "core rollback")')
  t.contains(source, 'core_result(runtime_instance, value, "core deletion")')
  t.eq(source:find('raw_outbound', 1, true), nil)
  t.eq(source:find('share_link', 1, true), nil)
end)

t.test("controller logs a safe uploaded core version summary", function()
  local source = read_file("luasrc/controller/xc.lua")
